"""Compile client/native/traffic.cpp to WebAssembly, embedded in a JS module.

Needs the compiler from requirements-build.txt. The output is kept in the source
tree, so building or running the game does not need a C++ toolchain.
"""
import base64
import subprocess
import sys
import tempfile
from pathlib import Path

CLIENT = Path(__file__).resolve().parent.parent / "client"
SOURCE = CLIENT / "native" / "traffic.cpp"
OUTPUT = CLIENT / "src" / "wasm" / "traffic-wasm.js"

with tempfile.TemporaryDirectory() as folder:
    wasm = Path(folder) / "traffic.wasm"
    subprocess.run(
        [sys.executable, "-m", "ziglang", "c++", "-target", "wasm32-freestanding",
         "-std=c++17", "-O3", "-nostdlib", "-fno-exceptions", "-fno-rtti",
         "-mbulk-memory", "-ffp-contract=off", "-Wall", "-Wextra",
         "-Wl,--no-entry", "-o", str(wasm), str(SOURCE)],
        check=True,
    )
    data = wasm.read_bytes()

OUTPUT.write_text(
    "// Generated by tools/build_wasm.py from native/traffic.cpp. Do not edit.\n"
    f"export default '{base64.b64encode(data).decode()}';\n"
)
print(f"{OUTPUT.name}: {len(data)} bytes of WebAssembly")
